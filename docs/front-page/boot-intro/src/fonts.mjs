// Lay out a word in a glyph table. Returns a Set of "x,y" grid cells.
// lean: shift row r right by floor((rows-1-r)/leanEvery) cells (an italic
// built from whole pixels, so edges stay crisp).
export function layoutCells(word, table, { gap = 1, leanEvery = 0 } = {}) {
  const cells = new Set();
  let x = 0;
  for (const ch of word) {
    const g = table[ch];
    if (!g) throw new Error(`no glyph ${ch}`);
    const rows = g.length;
    g.forEach((row, r) => {
      const lean = leanEvery ? Math.floor((rows - 1 - r) / leanEvery) : 0;
      [...row].forEach((bit, c) => { if (bit === '#') cells.add(`${x + c + lean},${r}`); });
    });
    x += g[0].length + gap;
  }
  return { cells, width: x - gap + (leanEvery ? Math.floor(8 / leanEvery) : 0) };
}

// Merge a set of cells into one compact path of horizontal runs.
export function cellsToPath(cells, s, ox = 0, oy = 0) {
  const byRow = new Map();
  for (const k of cells) {
    const [x, y] = k.split(',').map(Number);
    if (!byRow.has(y)) byRow.set(y, []);
    byRow.get(y).push(x);
  }
  let d = '';
  for (const [y, xs] of [...byRow].sort((a, b) => a[0] - b[0])) {
    xs.sort((a, b) => a - b);
    for (let i = 0; i < xs.length;) {
      let j = i;
      while (j + 1 < xs.length && xs[j + 1] === xs[j] + 1) j++;
      const w = (j - i + 1) * s;
      d += `M${ox + xs[i] * s} ${oy + y * s}h${w}v${s}h-${w}z`;
      i = j + 1;
    }
  }
  return d;
}

// Rows of '#'/'.' to a path at scale s.
export function glyphPath(rows, s = 1, ox = 0, oy = 0) {
  const cells = new Set();
  rows.forEach((row, r) => [...row].forEach((b, c) => { if (b === '#') cells.add(`${c},${r}`); }));
  return cellsToPath(cells, s, ox, oy);
}

export const mulberry32 = (a) => () => {
  a |= 0; a = (a + 0x6d2b79f5) | 0;
  let t = Math.imul(a ^ (a >>> 15), 1 | a);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
