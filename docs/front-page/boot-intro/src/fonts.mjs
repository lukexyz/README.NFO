// 8x8 bold: each FONT5 row ORed with itself shifted one pixel right, placed at
// column 1 so letters keep a one-pixel gap on both sides.
export function bold8(ch) {
  if (ch === '·') return ['........', '........', '........', '...##...', '...##...', '........', '........', '........'];
  const g = FONT5[ch] || FONT5[' '];
  const rows = [];
  for (let r = 0; r < 8; r++) {
    let row = '';
    for (let c = 0; c < 8; c++) {
      const sc = c - 1;
      const on = r < 7 && ((g[r][sc] === '#') || (g[r][sc - 1] === '#'));
      row += on ? '#' : '.';
    }
    rows.push(row);
  }
  return rows;
}

