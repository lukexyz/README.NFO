// Path data for a string in the pixel font: horizontal runs merged per row, all in one path.
export function pixelPath(str, x, y, px, advance = 6 * px) {
  let d = '';
  [...str.toUpperCase()].forEach((ch, i) => {
    const g = FONT[ch];
    if (!g) throw new Error(`pixel font has no glyph for ${JSON.stringify(ch)}`);
    g.forEach((row, ry) => {
      let run = -1;
      for (let rx = 0; rx <= 5; rx++) {
        const on = row[rx] === '1';
        if (on && run < 0) run = rx;
        if (!on && run >= 0) {
          d += `M${r(x + i * advance + run * px)} ${r(y + ry * px)}h${r((rx - run) * px)}v${r(px)}h${r(-(rx - run) * px)}z`;
          run = -1;
        }
      }
    });
  });
  return d;
}
// Width of a string: the last glyph ends after 5 pixels, not a full advance.
export const pixelWidth = (str, px, advance = 6 * px) => ([...str].length - 1) * advance + 5 * px;
const r = (n) => Math.round(n * 100) / 100;

