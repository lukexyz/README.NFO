export function logoGrid(word = 'README.NFO') {
  const rows = Array(6).fill('');
  for (const ch of word) {
    const g = G[ch];
    const w = Math.max(...g.map((row) => [...row].length));
    g.forEach((row, i) => { rows[i] += row.padEnd(w, ' ') + ' '; });
  }
  return rows.map((row) => [...row.replace(/\s+$/, '')]);
}

// Cell grid -> one path (full blocks merged into runs, half blocks as half-height boxes),
// so abutting cells never show anti-aliased seams at any scale.
export function cellPath(grid, ox, oy, cw, ch) {
  const out = [];
  const box = (x, y, w, h) => `M${r(x)} ${r(y)}h${r(w)}v${r(h)}h${r(-w)}z`;
  grid.forEach((row, y) => {
    let run = -1;
    for (let x = 0; x <= row.length; x++) {
      const c = row[x];
      if (c === '█' && run < 0) run = x;
      if (c !== '█' && run >= 0) { out.push(box(ox + run * cw, oy + y * ch, (x - run) * cw, ch)); run = -1; }
      if (c === '▀') out.push(box(ox + x * cw, oy + y * ch, cw, ch / 2));
      if (c === '▄') out.push(box(ox + x * cw, oy + y * ch + ch / 2, cw, ch / 2));
    }
  });
  return out.join('');
}

// CP437 shade glyphs as 2 px dot patterns: ░ 25 %, ▒ 50 %, ▓ 75 %.
export function shadePatterns(ink, bg, prefix = 's') {
  return `<pattern id="${prefix}1" width="4" height="4" patternUnits="userSpaceOnUse"><rect width="2" height="2" fill="${ink}"/></pattern>`
    + `<pattern id="${prefix}2" width="4" height="4" patternUnits="userSpaceOnUse"><rect width="2" height="2" fill="${ink}"/><rect x="2" y="2" width="2" height="2" fill="${ink}"/></pattern>`
    + `<pattern id="${prefix}3" width="4" height="4" patternUnits="userSpaceOnUse"><rect width="4" height="4" fill="${ink}"/><rect x="2" y="2" width="2" height="2" fill="${bg}"/></pattern>`;
}
export const shadeFill = (c, ink, prefix = 's') =>
  c === '█' ? ink : c === '▓' ? `url(#${prefix}3)` : c === '▒' ? `url(#${prefix}2)` : c === '░' ? `url(#${prefix}1)` : null;
