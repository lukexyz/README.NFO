// A run of type as <use> elements, in cell units. Returns { svg, width }.
// colourOf(i, ch) may group the glyphs into differently filled <g>s.
function textRun(str, { wt = 'r', track = 0, colourOf = null } = {}) {
  const groups = new Map();
  let x = 0;
  [...str].forEach((ch, i) => {
    if (ch !== ' ') {
      if (!GLYPH[wt][ch]) throw new Error(`no ${wt} glyph for "${ch}"`);
      usedGlyphs.add(`${wt}${ch}`);
      const key = colourOf ? colourOf(i, ch) : '';
      groups.set(key, (groups.get(key) || '') + `<use href="#${gid(wt, ch)}" x="${x}"/>`);
    }
    x += adv(wt, ch) + track;
  });
  const svg = [...groups].map(([fill, s]) => (fill ? `<g fill="${fill}">${s}</g>` : s)).join('');
  return { svg, width: x - 1 - track };
}
// centred line of type at pixel size px, top edge at y
