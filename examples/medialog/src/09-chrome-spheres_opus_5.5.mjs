// "Chrome spheres over a checkerboard" README banner for MediaLog.
//
//   node examples/medialog/src/09-chrome-spheres_opus_5.5.mjs
//
// Regenerates ../assets/09-chrome-spheres_opus_5.5.svg. Plain Node, no deps,
// deterministic (seeded PRNG, no clock). Two flags exist only for checking
// frames a long way into the loop without waiting for them:
//   --at=30        bake a 30 s head start into every animation delay
//   --out=file.svg write somewhere else (use this with --at, never in place)
//
// The style is the demoscene's own in-joke for "a demo": mirror balls over an
// endless checker floor under an italic chrome logo, a sky that runs a day,
// and a small scroller out at the horizon (Razor 1911's 2016 intro is the
// definitive one; nothing here is copied from it). The MediaLog reading:
//   * the six spheres are the six kinds in the pitch (film, show, book, game,
//     album, podcast), each in its own colour, riding a carousel;
//   * the hexagonal drum under the logo turns one face per sphere, so the line
//     always says the verb of the sphere at the front: WATCHED, READ, PLAYED,
//     LISTENED TO;
//   * the floor runs away from you into the haze, which is where things go
//     when you can only place them roughly: one sphere is already out there,
//     labelled SOMETIME IN 2015-2019;
//   * the sky starts at sunset and passes through every kind's colour once a
//     minute (plum, violet, magenta, red and amber at sunset, navy at night, teal
//     and green at dawn, blue by day).
//
// Everything is geometry from this file: the logo is parametric polygons (no
// font), small type is a 5x7 bitmap font (plus a bold cut derived from it)
// drawn as paths. No <text>. One small blur filter (the fogged sphere), no
// blend modes, no SMIL: CSS keyframes only.
//
// How the moving parts work
//   Floor: a checker is rows XOR columns. With the camera moving straight back
//   the column edges never move on screen (wedges fanning out of the vanishing
//   point), so the columns are two fixed clip paths. The rows are plain
//   rectangles that all make the same journey (y = HY + K / z, z changing at a
//   steady rate) on ONE shared @keyframes, played in reverse so the floor runs
//   away; they differ only in animation-delay. Rows under the odd wedges run
//   one tile out of step: that is the checker.
//   Carousel: each sphere rides one shared orbit track (translate + scale from
//   the floor's own projection, sampled every 7.5 degrees) with its own delay.
//   A front-half sphere can pass over a back-half one, so every sphere is
//   drawn twice, once in a back layer and once in a front layer, and each
//   copy is only visible on its half of the ring. The script then runs five
//   and a half minutes of orbit and bounce to prove that spheres sharing a
//   layer never touch.
//   Drum: a hexagonal prism seen face on. Face j at angle a is the flat face
//   translated by -apothem * sin(a) and squashed by cos(a); all six faces
//   share one keyframe track, one slot apart.
//   Sky: the day is the base. Sunset, night and dawn skies are opaque groups
//   stacked on top (each with its own haze, so the horizon never shows a
//   seam): sunset is up at frame 0, night comes in over it, dawn over night,
//   then all three let go together into day, and sunset returns. The tints
//   on the floor and on every lit thing (logo, drum, spheres) are
//   translucent, so they simply cross-fade from one hour to the next.
//   prefers-reduced-motion pauses everything on frame 0: the complete sunset.
// (The .md beside the assets is hand-written, not generated by this script.)

