export const esc = (value) => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
export const option = (number) => {
  const result = DRAW.options.find((pick) => pick.number === number);
  if (!result) throw new Error(`Unknown candidate ${number}`);
  return result;
};

