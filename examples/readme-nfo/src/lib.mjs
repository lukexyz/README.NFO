export const width = (text, scale = 2) => Math.max(0, String(text).length * 6 - 1) * scale;
export function px(text, x, y, scale = 2, fill = '#ffffff', attrs = '') {
  let d = '';
  for (const [index, character] of [...String(text).toUpperCase()].entries()) {
    const glyph = FONT[character] || FONT['?'];
    for (let row = 0; row < 7; row++) for (let col = 0; col < 5; col++) {
      if (glyph[row] & (1 << (4-col))) d += `M${index*6+col} ${row}h1v1h-1z`;
    }
  }
  return `<g transform="translate(${x} ${y}) scale(${scale})" ${attrs}><path d="${d}" fill="${fill}"/></g>`;
}
export const center = (text, y, scale = 4, fill = '#ffffff', canvas = 960, attrs = '') => px(text, (canvas-width(text,scale))/2, y, scale, fill, attrs);
export function svg({ width: w = 960, height: h = 360, background = '#080e18', defs = '', css = '', body, title = INFO.name, description = '' }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 ${w} ${h}" role="img" aria-labelledby="title desc">
<title id="title">${esc(title)}</title><desc id="desc">${esc(description)}</desc>
<defs>${defs}</defs><style>${css}\n@media(prefers-reduced-motion:reduce){*{animation:none!important;transition:none!important}}</style>
<rect width="${w}" height="${h}" fill="${background}"/>${body}</svg>\n`;
}

export function writeHeader(number, { image, markdown, alt, summary }) {
  const pick = option(number);
  const padded = String(number).padStart(2,'0');
  fs.mkdirSync(path.join(DIR,'assets'),{recursive:true});
  if (image) fs.writeFileSync(path.join(DIR,'assets',`${pick.slug}.svg`),image);
  const header = markdown ?? [
    '<p align="center">',
    `  <img src="assets/${pick.slug}.svg" width="100%" alt="${esc(alt || summary)}">`,
    '</p>', '',
    '<p align="center"><b>README.NFO</b> — retro headers for your next repository.<br>',
    '152 styles, thirteen families, text art and animated SVG. Pick a look. Make it yours.</p>', '',
    '<p align="center"><a href="../../styles/INDEX.md">Style catalogue</a> · <a href="../README.md">Example galleries</a> · <a href="../../LICENSE">MIT licence</a></p>',
  ].join('\n');
  const body = [
    `<!-- README.NFO candidate ${padded}; generated by src/${pick.slug}.mjs. -->`, '', header, '',
    `> **Candidate ${padded}** · [${pick.id}](../../styles/${pick.family}.md#${pick.id}) · ${summary}`, '',
    `[Generator](src/${pick.slug}.mjs) · [All candidates](README.md)`, '',
  ].join('\n');
  fs.writeFileSync(path.join(DIR,`${pick.slug}.md`),body);
  console.log(`wrote candidate ${padded}: ${pick.slug}`);
}
