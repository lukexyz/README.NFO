// The rest of the factory, a long way off: two layers of silhouette standing
// on the horizon behind the production line, a few lit windows and a red
// beacon on every chimney. It has its own PRNG, so the stars and the furnace
// fire keep their seeds.
const SKYLINE = (() => {
  const r = mulberry32(0x51de);
  const ri = (a, b) => a + Math.floor(r() * (b - a + 1));
  const far = new Grid(W, H);
  const near = new Grid(W, H);
  const lit = [];
  const beacons = [];
  const col = (g, x, top) => { for (let y = top; y < FLOOR_Y; y++) g.set(x, y); };
  for (let x = -3; x < W;) { // far: tall halls, stepped roofs, chimneys
    const w = ri(10, 24);
    const top = FLOOR_Y - ri(16, 27);
    for (let i = 0; i < w; i++) col(far, x + i, top);
    const kind = r();
    if (kind < 0.45) {
      const cx = x + ri(1, w - 4);
      const ct = top - ri(4, 8);
      col(far, cx, ct); col(far, cx + 1, ct);
      beacons.push([cx, ct - 1]);
    } else if (kind < 0.75) {
      for (let i = 3; i < w - 3; i++) col(far, x + i, top - 2);
    }
    x += w + (r() < 0.35 ? ri(4, 10) : 0);
  }
  for (let x = -2; x < W;) { // near: sheds, domed tanks, pipe racks
    const kind = r();
    const w = ri(7, 16);
    const top = FLOOR_Y - ri(9, 17);
    if (kind < 0.3) { // tank: a dome with its corners knocked off
      for (let i = 0; i < w; i++) col(near, x + i, top + (i === 0 || i === w - 1 ? 2 : i === 1 || i === w - 2 ? 1 : 0));
    } else if (kind < 0.5) { // pipe rack: a line on legs
      for (let i = 0; i < w; i++) { near.set(x + i, top + 2); near.set(x + i, top + 4); if (i % 4 === 0) col(near, x + i, top + 2); }
    } else { // shed, maybe with a lit window or two
      for (let i = 0; i < w; i++) col(near, x + i, top);
      for (let i = 2; i < w - 2; i += 3) if (r() < 0.45 && top + 2 < BELT_Y - 2) lit.push([x + i, top + 2]);
    }
    x += w + ri(0, 7);
  }
  return { far: gridPath(far), near: gridPath(near), lit, beacons };
})();

