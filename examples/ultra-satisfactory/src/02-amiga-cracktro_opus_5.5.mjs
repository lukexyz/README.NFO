// Loop maths
//   Scroller: moves at SPEED px/s through a stationary sine of WAVE px. A
//   character at screen x has y = AMP*sin(2*pi*x/WAVE), so every character
//   bobs with period WAVE/SPEED and a phase set by its index modulo WAVE/8.
//   Characters that share a phase share one animated <g>. The text is padded
//   to a whole number of wavelengths, so after one full scroll the duplicated
//   head of the text sits exactly where the original started, in the same
//   phase: no jump at the loop point.
//   Belt: every segment carries a repeating pattern of items and slides by
//   exactly one pattern length per loop, so the wrap is invisible.
//   Cogs: an N-tooth cog is drawn at 4 angles across one tooth pitch and the
//   frames are flipped through, which loops every tooth.

