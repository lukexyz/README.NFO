// ------------------------------------------------ closing conveyor rule SVG
// A strip of belt that closes the header: one of everything rides past, over a
// colour-cycling floor line. Slides exactly one pattern length per loop.
{
  const RH = 16;
  const by = 11; // belt surface row
  const order = ['ingotFe', 'plate', 'screw', 'frame', 'ingotCu', 'rods', 'coil', 'frame'];
  const period = order.length * SLOT;
  const itemDefs = Object.entries(ITEMS).map(([name, s]) => `<g id="i-${name}">${s.svg()}</g>`).join('');
  let uses = '';
  for (let k = 0, x = -period; x < W; k++, x += SLOT) {
    const name = order[k % order.length];
    const s = ITEMS[name];
    uses += `<use href="#i-${name}" x="${x + Math.floor((SLOT - s.w) / 2)}" y="${by - s.h}"/>`;
  }
  let cleats = '';
  for (let x = -8; x < W; x += 8) cleats += `M${x} ${by + 1}h2v2h-2z`;
  const floor = HUES.map((c, h) => {
    let d = '';
    for (let m = 0; m < 7; m++) d += `M${h * 4 + m * 64} ${RH - 1}h4v1h-4z`;
    return `<path fill="${c}" d="${d}"/>`;
  }).join('');
  const rule = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${RH}" width="${W * 3}" height="${RH * 3}" shape-rendering="crispEdges" role="img" aria-labelledby="t">
<title id="t">A conveyor belt carrying pixel ingots, plates, screws and frames</title>
<style>.it{animation:it ${n(period / BELT_SPEED)}s linear infinite}@keyframes it{from{transform:translateX(0)}to{transform:translateX(${period}px)}}.bt{animation:bt ${n(8 / BELT_SPEED)}s linear infinite}@keyframes bt{from{transform:translateX(0)}to{transform:translateX(8px)}}.rb{animation:rb 1.6s linear infinite}@keyframes rb{from{transform:translateX(0)}to{transform:translateX(-64px)}}@media (prefers-reduced-motion:reduce){*{animation:none!important}}</style>
<defs><clipPath id="c"><rect width="${W}" height="${RH}" rx="3"/></clipPath>${itemDefs}</defs>
<g clip-path="url(#c)"><rect width="${W}" height="${RH}" fill="${BG}"/>
<path fill="#b4bedc" d="M0 ${by}h${W}v1h-${W}z"/><path fill="#262b40" d="M0 ${by + 1}h${W}v2h-${W}z"/><path fill="#10121c" d="M0 ${by + 3}h${W}v1h-${W}z"/>
<path class="bt" fill="#5d6688" d="${cleats}"/>
<g class="it">${uses}</g>
<g class="rb">${floor}</g></g>
</svg>
`;
  fs.writeFileSync(RULE, rule);
  console.log(`wrote ${path.relative(process.cwd(), RULE)} (${(rule.length / 1024).toFixed(1)} KB)`);
}
