function inPoly(px, py, poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if ((yi > py) !== (yj > py) && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function rasterWord(text, L, LH, gap, y0, depth) {
  const width = [...text].reduce((w, c, i) => w + L[c].w + (i < text.length - 1 ? gap : 0), 0);
  const x0 = Math.round((W - width - depth) / 2);
  const face = new Grid(W, H);
  const boxes = [];
  let x = x0;
  for (const c of text) {
    const l = L[c];
    boxes.push({ c, x, w: l.w });
    for (let yy = 0; yy < LH; yy++) {
      for (let xx = 0; xx < l.w; xx++) {
        const px = xx + 0.5;
        const py = yy + 0.5;
        if (l.add.some((p) => inPoly(px, py, p)) && !l.sub.some((p) => inPoly(px, py, p))) face.set(x + xx, y0 + yy);
      }
    }
    x += l.w + gap;
  }
  // 3D extrusion down-right.
  const extrude = new Grid(W, H);
  for (let d = 1; d <= depth; d++) {
    for (let y = 0; y < H; y++) for (let xx = 0; xx < W; xx++) {
      if (face.get(xx, y) && !face.get(xx + d, y + d) && !extrude.get(xx + d, y + d)) extrude.set(xx + d, y + d, d);
    }
  }
  return { face, extrude, boxes, x0, width, y0, LH, depth };
}

