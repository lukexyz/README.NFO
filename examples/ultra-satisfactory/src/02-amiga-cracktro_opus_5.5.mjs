function drawTiny(set, s, x, y) {
  for (const ch of s) {
    if (ch === ' ') { x += 3; continue; }
    const g = F5[ch];
    if (!g) throw new Error(`tiny font lacks ${JSON.stringify(ch)}`);
    g.forEach((row, r) => [...row].forEach((c, k) => { if (c === '#') set(x + k, y + r); }));
    x += g[0].length + 1;
  }
  return x;
}
