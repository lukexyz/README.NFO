const hexPoly = (r) => Array.from({ length: 6 }, (_, k) => {
  const a = ((-90 + 60 * k) * Math.PI) / 180;
  return [EMC + 0.5 + r * Math.cos(a), EMC + 0.5 + r * Math.sin(a)];
});
function cogGrid(size, cx, cy, teeth, rBody, rTeeth, rHole, toothDeg, rotDeg) {
  const g = new Grid(size, size);
  const pitch = 360 / teeth;
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const dx = x - cx;
    const dy = y - cy;
    const r = Math.hypot(dx, dy);
    if (r < rHole) continue;
    const a = (((Math.atan2(dy, dx) * 180) / Math.PI - rotDeg) % pitch + pitch) % pitch;
    const tooth = a < toothDeg / 2 || a > pitch - toothDeg / 2;
    if (r <= rBody || (r <= rTeeth && tooth)) g.set(x, y);
  }
  return g;
}
// Shade a cog: highlight on the top-left rim, shadow on the bottom-right rim.
function cogSprite(g, [base, hi, lo]) {
  const s = new Sprite(g.w, g.h);
  for (let y = 0; y < g.h; y++) for (let x = 0; x < g.w; x++) {
    if (!g.get(x, y)) continue;
    s.px(x, y, !g.get(x + 1, y + 1) ? lo : !g.get(x - 1, y - 1) ? hi : base);
  }
  return s;
}
