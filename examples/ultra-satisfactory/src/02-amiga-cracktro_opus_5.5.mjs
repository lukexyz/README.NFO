function starLayer(count, w = 1, bands = STAR_BANDS) {
  const g = new Grid(W * 2, H);
  for (let i = 0; i < count; i++) {
    const x = Math.floor(rand() * W);
    const y = 3 + Math.floor(rand() * (H - 6));
    if (bands.some(([a, b]) => y >= a && y <= b)) { i--; continue; }
    for (let k = 0; k < w; k++) { g.set(x + k, y); g.set(x + k + W, y); }
  }
  return gridPath(g);
}
