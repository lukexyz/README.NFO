// Parametric capitals drawn for this banner: wide, heavy, and "sliced". Every
// big cut runs the same way as the italic slope (/): the top-left of a stem or
// bowl, the bottom-right of a bowl, and the free end of every bar.
function glyph(ch, { w, h, s, t }) {
  const C = s * 0.62;            // stem-tip cut
  const CB = Math.min(w, h) * 0.34; // bowl cut
  const c = s * 0.2;             // the small opposite chamfer
  const d = t * 0.6;             // slope of a bar's free end
  const ci = Math.max(2, CB - 0.293 * (s + t)); // inner cut parallel to CB
  const a = (w - s) / 2, b = (w + s) / 2;
  switch (ch) {
    case 'U': return { adv: w, polys: [[[0, C], [C, 0], [s, 0], [s, h - t], [w - s - ci, h - t], [w - s, h - t - ci], [w - s, C], [w - s + C, 0], [w, 0], [w, h - CB], [w - CB, h], [c, h], [0, h - c]]] };
    case 'L': { const lw = w * 0.84; return { adv: lw, polys: [[[0, C], [C, 0], [s, 0], [s, h - t], [lw, h - t], [lw - d, h], [c, h], [0, h - c]]] }; }
    case 'T': return { adv: w, polys: [[[d, 0], [w, 0], [w - d, t], [b, t], [b, h - C], [b - C, h], [a, h], [a, t], [0, t]]] };
    case 'R': {
      const m = h * 0.56, lw = s * 1.1, la = s + (w - 2 * s) * 0.2, cb = CB * 0.8, cj = Math.max(2, cb - 0.293 * (s + t));
      return { adv: w, polys: [
        [[0, C], [C, 0], [w - c, 0], [w, c], [w, m - cb], [w - cb, m], [la + lw, m], [w, h], [w - lw, h], [la, m], [s, m], [s, h - C], [s - C, h], [0, h]],
        [[s, t], [w - s, t], [w - s, m - t - cj], [w - s - cj, m - t], [s, m - t]],
      ] };
    }
    case 'A': {
      const xl = w * 0.29, s2 = s * 1.06, run = xl / h, y1 = h * 0.6, y2 = y1 + t * 0.85;
      const inL = (y) => s2 + (h - y) * run;
      const ya = h - (w / 2 - s2) / run; // where the inner edges meet
      const top = ya > t * 0.9 ? [[w / 2, ya]] : [[inL(t), t], [w - inL(t), t]];
      return { adv: w, polys: [
        [[0, h], [xl, 0], [w - xl, 0], [w, h], [w - s2, h], [w - inL(y2), y2], [inL(y2), y2], [s2, h]],
        [...top, [w - inL(y1), y1], [inL(y1), y1]],
      ] };
    }
    case 'S': {
      const m0 = (h - t) / 2, m1 = (h + t) / 2;
      return { adv: w, polys: [[[CB, 0], [w, 0], [w - d, t], [s + ci, t], [s, t + ci], [s, m0], [w - c, m0], [w, m0 + c], [w, h - CB], [w - CB, h], [0, h], [d, h - t], [w - s - ci, h - t], [w - s, h - t - ci], [w - s, m1], [c, m1], [0, m1 - c], [0, CB]]] };
    }
    case 'I': { const iw = s * 1.08; return { adv: iw, polys: [[[0, C], [C, 0], [iw, 0], [iw, h - C], [iw - C, h], [0, h]]] }; }
    case 'F': { const fw = w * 0.92, m = h * 0.43, bt = t * 0.9, mw = fw * 0.8; return { adv: fw, polys: [[[0, C], [C, 0], [fw, 0], [fw - d, t], [s, t], [s, m], [mw, m], [mw - d, m + bt], [s, m + bt], [s, h - C], [s - C, h], [0, h]]] }; }
    case 'C': return { adv: w, polys: [[[CB, 0], [w, 0], [w - d, t], [s + ci, t], [s, t + ci], [s, h - t], [w, h - t], [w - d, h], [c, h], [0, h - c], [0, CB]]] };
    case 'O': return { adv: w, polys: [
      [[CB, 0], [w - c, 0], [w, c], [w, h - CB], [w - CB, h], [c, h], [0, h - c], [0, CB]],
      [[s + ci, t], [w - s, t], [w - s, h - t - ci], [w - s - ci, h - t], [s, h - t], [s, t + ci]],
    ] };
    case 'Y': {
      const sa = s * 1.12, jy = h * 0.5, vy = (jy * (w / 2 - sa)) / a;
      return { adv: w, polys: [[[0, 0], [sa, 0], [w / 2, vy], [w - sa, 0], [w, 0], [b, jy], [b, h - C], [b - C, h], [a, h], [a, jy]]] };
    }
    default: throw new Error(`no logo glyph ${ch}`);
  }
}
const area2 = (p) => p.reduce((acc, [x1, y1], i) => { const [x2, y2] = p[(i + 1) % p.length]; return acc + x1 * y2 - x2 * y1; }, 0);
// Normalise winding so the metal is always on the right of each edge.
const wind = (p, clockwise) => ((area2(p) > 0) === clockwise ? p : [...p].reverse());
// Unit normal pointing into the metal, per edge.
function edgeNormals(p) {
  return p.map(([x1, y1], i) => {
    const [x2, y2] = p[(i + 1) % p.length];
    const dx = x2 - x1, dy = y2 - y1, l = Math.hypot(dx, dy);
    return [-dy / l, dx / l];
  });
}
// Mitred inset of a polygon by b, towards the metal.
function inset(p, b) {
  const nn = edgeNormals(p);
  return p.map(([x, y], i) => {
    const u = nn[(i + p.length - 1) % p.length], v = nn[i];
    const k = b / Math.max(0.4, 1 + u[0] * v[0] + u[1] * v[1]);
    return [x + (u[0] + v[0]) * k, y + (u[1] + v[1]) * k];
  });
}

