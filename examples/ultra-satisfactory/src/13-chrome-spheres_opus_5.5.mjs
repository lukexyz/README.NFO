// The same scene for text terminals, from the same projection: prints an
// 80-column checker floor with three of the spheres bouncing over it. Paste it
// into the .md by hand.
if (process.argv.includes('--ascii')) {
  const COLS = 80, FLOOR_ROWS = 9, SKY = 5;
  const eye = 1.3, Ka = (FLOOR_ROWS * 2 - 1) * ZB;
  const grid = [];
  for (let i = 0; i < SKY; i++) grid.push(Array(COLS).fill(' '));
  for (let r = 0; r < FLOOR_ROWS; r++) {
    const y = r * 2 + 1, z = Ka / y, tw = y / eye;
    const row = [];
    for (let c = 0; c < COLS; c++) {
      if (tw < 1.5) { row.push(c % 2 ? '.' : ' '); continue; } // haze
      const X = (c - COLS / 2 + 0.5) / tw - 0.5;
      row.push(((Math.floor(X + 100) + Math.floor(z)) & 1) ? '#' : ' ');
    }
    grid.push(row);
  }
  const BALL = [
    '  .-"""-.',
    ' /  o    \\',
    '|=========|',
    ' \\ # # # /',
    "  `-...-'",
  ];
  const stamp = (lines, col, top) => lines.forEach((line, i) => {
    const first = line.search(/\S/);
    // one clear cell either side, so the outline does not run into the tiles
    [...` ${line.slice(first)} `].forEach((ch, j) => { if (grid[top + i]) grid[top + i][col + first - 1 + j] = ch; });
  });
  // [column, top row, row of the shadow]
  for (const [c, t, sh] of [[5, 2, 9], [34, 5, 12], [63, 1, 8]]) {
    stamp(['  (:::::)'], c, sh);
    stamp(BALL, c, t);
  }
  console.log(grid.map((r) => r.join('').trimEnd()).join('\n'));
}
