// "Chrome spheres over a checkerboard" README banner for ULTRA-SATISFACTORY.
//
//   node examples/ultra-satisfactory/src/13-chrome-spheres_opus_5.5.mjs
//   node examples/ultra-satisfactory/src/13-chrome-spheres_opus_5.5.mjs --ascii
//
// Regenerates ../assets/13-chrome-spheres_opus_5.5.svg. With --ascii it also
// prints the 80-column checker floor used in the .md's text block (same
// projection as the SVG floor). Plain Node, no deps, deterministic (seeded
// PRNG, no clock). Two more flags exist only for checking frames that are a
// long way into the loop without waiting for them:
//   --at=30        bake a 30 s head start into every animation delay
//   --out=file.svg write somewhere else (use this with --at, never in place)
//
// The style is the demoscene's own in-joke for "a demo", played straight in
// Razor 1911's 2016 cracktro (code XT95, logo Sprocket): mirror balls bouncing
// over an endless checker floor under an italic chrome logo, with the sky
// running a day-night cycle and a small scroller out at the horizon. Nothing
// here is copied from it: the letterforms, spheres and copy are drawn for this
// banner. The factory reading: the floor is foundations to the horizon, and
// the six spheres are the only things on site with nothing missing.
//
// Everything is geometry from this file: the logo is parametric polygons (no
// font), small type is a 5x7 bitmap font drawn as paths. No <text>, no filters,
// no blend modes, no SMIL: CSS keyframes only.
//
// How the moving parts work
//   Floor: a checker is (rows XOR columns). Flying forward never moves the
//   column boundaries on screen (they are wedges fanning out of the vanishing
//   point), so the columns are two static clip paths, even wedges and odd
//   wedges. The rows are plain full-width rects. Every row follows the same
//   journey from the horizon to the bottom edge, y = HY + K / z with z falling
//   at a steady rate, so all of them share ONE @keyframes (sampled densely
//   where the hyperbola bends) and differ only in animation-delay. The rows
//   under the odd wedges run one tile out of step with the rows under the
//   even wedges, and that is the checker. Sideways drift is one more transform
//   on the parent: a lateral camera move is exactly a skewX about the horizon
//   line, and the pattern repeats every two tiles, so the skew loops.
//   Spheres: a mirror ball over a floor shows that floor's columns as wedges
//   fanning out of the ball's centre (that part is exact) and its rows as
//   nested arcs collapsing onto the equator (here: nested ellipses in a
//   geometric ladder, so a scaleY by the ladder's ratio squared maps the rings
//   onto themselves and the zoom loops). Same two-clip trick, same skew.
//   Day and night: the day scene is the base. Dusk and night are two groups
//   fading in and out on one 60 s timeline, each holding that hour's whole
//   backdrop (sky, floor tint, haze) so sky and haze fade as one layer and the
//   horizon never shows a seam. Every other lit thing (logo, spheres) carries a
//   dusk tint and a night tint on the same two classes. The sun and moon sit
//   at opposite ends of one wheel turning about the horizon's centre, clipped
//   at the horizon so they set behind the floor.
//   prefers-reduced-motion pauses everything on frame 0, which is the complete
//   daytime scene.
// (The .md beside the assets is hand-written, not generated by this script.)

