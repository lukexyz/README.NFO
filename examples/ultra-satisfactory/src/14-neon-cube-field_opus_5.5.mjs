  css.push(`use{animation:${FLD.T}s ${ease} infinite}`);
  for (const k of [...usedK].sort((a, b) => a - b)) {
    if (!k) continue;
    const q = k / FLD.levels;
    const A = n1(FLD.amp * q), s0 = n(1 - FLD.grow * q, 3), s1 = n(1 + FLD.grow * q, 3);
    css.push(`@keyframes k${k}{0%,100%{transform:translateY(${A}px) scale(${s0})}50%{transform:translateY(-${A}px) scale(${s1})}}.${LVL_CLASS(k)}{animation-name:k${k}}`);
  }
  css.push([...usedP].sort((a, b) => a - b).map((p) => `.${PH_CLASS(p)}{animation-delay:${n((-p * FLD.T) / FLD.phases, 2)}s}`).join(''));

  // Colour and light without a single per-cube colour animation:
  //   1. underneath everything, a repeating rainbow gradient banded along the
  //      floor's i axis, sliding sideways once per LOOP (the hue sweep);
  //   2. on top of it the grey floor and cubes as one group with
  //      mix-blend-mode:hard-light, which turns black into black, mid grey
  //      into the hue below and white into white;
  //   3. inside that group, one soft band gradient per wave component (white
  //      on the crest line, black in the trough), sliding at the wave's own
  //      speed, so crests flare and troughs fall into shade.
  // Three sliding rects, however many cubes there are.
  const slide = (id, sw, list, dur) => {
    defs.push(`<linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="${n1(sw.x1)}" y1="${n1(sw.y1)}" x2="${n1(sw.x2)}" y2="${n1(sw.y2)}" spreadMethod="repeat">${stops(list)}</linearGradient>`);
    const P = Math.abs(sw.px), right = sw.px > 0;
    css.push(`@keyframes ${id}{to{transform:translateX(${right ? '' : '-'}${n1(P)}px)}}.${id}{animation:${id} ${dur}s linear infinite}`);
    return `<rect class="${id}" x="${n1(right ? -P : 0)}" y="${FLD.top}" width="${n1(W + P)}" height="${H - FLD.top}" fill="url(#${id})"/>`;
  };
  const rainbow = slide('rb', screenWave(TAU * HUE_PER_I, 0, -TAU * HUE_AT_0), [...WHEEL, WHEEL[0]].map((c, k) => [n(k / WHEEL.length, 2), c]), LOOP);
  const bands = WAVES.map((w, k) => {
    // crest where the component's phase is ph - pi/2 at t = 0
    const share = w.a / WSUM;
    const hi = n(LIGHT.crest * share, 3), lo = n(LIGHT.trough * share, 3);
    const list = [[0, '#fff', hi], [0.25, '#fff', 0], [0.25, '#000', 0], [0.5, '#000', lo], [0.75, '#000', 0], [0.75, '#fff', 0], [1, '#fff', hi]];
    return slide(`sh${k}`, screenWave(w.ki, w.kj, w.ph - Math.PI / 2), list, FLD.T);
  });
  css.push('.hl{mix-blend-mode:hard-light}');
  // the floor under the cubes: a dark grey, so a little of the hue glows through
  defs.push(`<radialGradient id="haze" gradientUnits="userSpaceOnUse" cx="${W / 2}" cy="330" r="560" gradientTransform="translate(0 330) scale(1 .5) translate(0 -330)">${stops(CUBE.floor)}</radialGradient>`);
