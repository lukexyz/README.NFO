// "Neon cube field" README banner for ULTRA-SATISFACTORY.
//
//   node examples/ultra-satisfactory/src/14-neon-cube-field_opus_5.5.mjs
//   node examples/ultra-satisfactory/src/14-neon-cube-field_opus_5.5.mjs --ascii
//
// Regenerates ../assets/14-neon-cube-field_opus_5.5.svg (the banner) and
// ../assets/14-neon-cube-field_opus_5.5-rule.svg (a divider: a row of spinning
// glenz octahedra). With --ascii it also prints the text-mode cube wave used
// in the .md's info file. Plain Node, no deps, deterministic (a seeded PRNG
// places the stars; no clock, no Math.random).
// (The .md beside the assets is hand-edited, not generated by this script. It
// quotes the cube count, the wave numbers and the 64k size limit: see the
// console output, and the size check near the end.)
//
// The look is the 2010-2012 Windows 64k-intro / cracktro revival (the style
// people call "the rez-era Razor 1911 look"): a field of hundreds of small
// glowing cubes that reads as one rainbow ramp, rolling in a wave; a segmented
// LCD-like wordmark pinned top centre; a text writer; scanlines over the lot.
// Nothing of theirs is reproduced: the wordmark is a generic segment display
// drawn from geometry in this file, the small type is a 5x7 bitmap font drawn
// as paths, and the crew name is made up. No <text>, one small blur filter
// (the wordmark's glow). The factory reading: the cubes are a floor of
// foundations, and the three signs standing on it are the app's three tabs.
//
// How it moves (every period divides LOOP = 32 s, bar the starfield, which
// wraps on its own, so nothing ever jumps)
//   Wave: the floor height is a sum of plane waves that share one period. A
//   sum of same-frequency sines is itself a sine at every point,
//   R(p) sin(wt + P(p)), so each cube needs only an amplitude (one of a few
//   @keyframes: up, down, and slightly bigger at the top) and a phase (a
//   negative animation-delay). Each cube is one <use> of one grey symbol and
//   animates nothing but its transform.
//   Colour: animating an inherited fill on hundreds of <use> elements costs a
//   style recalculation per cube per frame (about 10 fps when measured in
//   headless Chrome; this version measured at the full 60).
//   So the cubes are grey and the colour is done by blending: a rainbow
//   gradient slides underneath and the grey layer goes over it with
//   mix-blend-mode:hard-light (black stays black, mid grey shows the hue,
//   white stays white). Crests and troughs are lit by one sliding band
//   gradient per wave component inside the grey layer. Three sliding rects.
//   Where blend modes are missing the floor simply shows in greys.
//   Text writer: four pages on one 32 s timeline. Page 1 is already typed at
//   t = 0 (so the first frame, and the reduced-motion frame, is complete) and
//   is re-typed at the end of the loop. Typing is a background-coloured cover
//   stepping away one character at a time, the cursor riding its edge.

