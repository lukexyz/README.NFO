// glyph ids: a letter is its own id, anything else is _ plus its code point
const gid = (ch) => (/[A-Za-z]/.test(ch) ? ch : `_${ch.codePointAt(0).toString(36)}`);
// Lit cells as a compact path: horizontal runs, merged down rows.
function cellsPath(rows) {
  const rects = [];
  let active = new Map();
  rows.forEach((row, y) => {
    const next = new Map();
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      let x1 = x;
      while (x1 < row.length && row[x1] === '#') x1++;
      const key = `${x},${x1}`;
      const r = active.get(key);
      if (r) { r.h++; next.set(key, r); } else { const nr = { x, y, w: x1 - x, h: 1 }; rects.push(nr); next.set(key, nr); }
      x = x1;
    }
    active = next;
  });
  return rects.map((r) => `M${r.x} ${r.y}h${r.w}v${r.h}h${-r.w}z`).join('');
}
const usedGlyphs = new Set();
// Small type: 5x7 cells, one user unit per cell (scale the group), <use> per glyph.
function textUses(str, col0 = 0, cell = 6) {
  let s = '';
  [...str].forEach((ch, i) => {
    if (ch === ' ') return;
    if (!FONT[ch]) throw new Error(`no glyph for "${ch}"`);
    usedGlyphs.add(ch);
    s += `<use href="#${gid(ch)}" x="${(col0 + i) * cell}"/>`;
  });
  return s;
}
