// Lit cells as a compact path: horizontal runs, merged down rows.
function cellsPath(rows) {
  const rects = [];
  let active = new Map();
  rows.forEach((row, y) => {
    const next = new Map();
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      let x1 = x;
      while (x1 < row.length && row[x1] === '#') x1++;
      const key = `${x},${x1}`;
      const r = active.get(key);
      if (r) { r.h++; next.set(key, r); } else { const nr = { x, y, w: x1 - x, h: 1 }; rects.push(nr); next.set(key, nr); }
      x = x1;
    }
    active = next;
  });
  return rects.map((r) => `M${r.x} ${r.y}h${r.w}v${r.h}h${-r.w}z`).join('');
}
// Glyph <defs> are emitted once per prefix ('t' pixel type, 'p' dot-matrix),
// only for the characters actually used.
const usedGlyphs = { t: new Set(), p: new Set() };
function needGlyph(prefix, ch) {
  if (ch === ' ') return null;
  if (!FONT[ch]) throw new Error(`no glyph for "${ch}"`);
  usedGlyphs[prefix].add(ch);
  return gid(prefix, ch);
}

