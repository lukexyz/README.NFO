// Win32 "new old-school" cracktro README banner for ULTRA-SATISFACTORY.
//
//   node examples/ultra-satisfactory/src/11-win32-cracktro_opus_5.5.mjs
//   node examples/ultra-satisfactory/src/11-win32-cracktro_opus_5.5.mjs --ascii
//
// Regenerates ../assets/11-win32-cracktro_opus_5.5.svg. With --ascii it also
// prints the text-mode twister used in the .md's NFO block (same maths as the
// SVG one). Plain Node, no deps, deterministic (seeded PRNG, no clock).
//
// The look is the 2004-2011 Windows cracktro revival: a bevelled, extruded
// vector-chrome logo standing on a mirror floor, a sine-twister each side, a
// text-writer block and a dot-matrix sine scroller. The factory reading: the
// twisters are square girders (hazard tape, riveted plate, a light bar and a
// lattice face) being wrung out between two chucks.
//
// Everything is drawn from geometry defined in this file: the logo letters are
// parametric polygons (no font), the small type is a 5x7 bitmap font drawn as
// paths, the scroller is the same font as round dots. No <text>, no filters.
// (The .md beside the assets is hand-edited, not generated by this script.)
//
// Loop maths
//   Twister: a square column whose rotation angle at row y and time t is
//   theta(t + y*d), one periodic function sampled into two @keyframes (one
//   per pair of opposite faces: left edge, width, brightness, and which of
//   the two is showing). Every row is two <g> elements sharing those
//   keyframes with a negative animation-delay, so the twist travels along the
//   column and the loop is seamless. 60 rows x 2 x 2 columns = 240 animated
//   elements; that count is what the banner costs to play, so keep it low.
//   Scroller: moves at SPEED px/s through a stationary sine, PHASES characters
//   long. Characters that share a phase (index mod PHASES) share one bobbing
//   <g>. The text is padded to a whole number of wavelengths and its head is
//   repeated after the tail, so the wrap is invisible.
//   Text-writer: three pages on one timeline. Page 1 is already typed at t=0
//   (so the first frame, and the reduced-motion frame, is complete) and
//   re-types at the end of the loop. Typing is a floor-coloured cover stepping
//   away one character at a time, with the cursor riding its leading edge.

