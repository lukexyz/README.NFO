const area2 = (p) => p.reduce((a, [x1, y1], i) => { const [x2, y2] = p[(i + 1) % p.length]; return a + x1 * y2 - x2 * y1; }, 0);
// Normalise winding so the metal is always on the right of each edge
// (outlines clockwise on screen, counters anticlockwise).
const wind = (p, clockwise) => ((area2(p) > 0) === clockwise ? p : [...p].reverse());
// Unit normal pointing into the metal, per edge.
function edgeNormals(p) {
  return p.map(([x1, y1], i) => {
    const [x2, y2] = p[(i + 1) % p.length];
    const dx = x2 - x1, dy = y2 - y1, l = Math.hypot(dx, dy);
    return [-dy / l, dx / l];
  });
}
// Mitred inset of a polygon by b, towards the metal.
function inset(p, b) {
  const nn = edgeNormals(p);
  return p.map(([x, y], i) => {
    const a = nn[(i + p.length - 1) % p.length], c = nn[i];
    const k = b / Math.max(0.35, 1 + a[0] * c[0] + a[1] * c[1]);
    return [x + (a[0] + c[0]) * k, y + (a[1] + c[1]) * k];
  });
}

