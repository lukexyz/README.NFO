const used5 = new Set();
// x, y in virtual px; 6 px advance. Fill comes from the group class.
function text5(str, x, y, cls) {
  const out = [];
  let cx = x;
  for (const ch of str.toUpperCase()) {
    if (ch !== ' ' && FONT5[ch]) {
      used5.add(ch);
      out.push(`<use href="#f${ch.codePointAt(0)}" x="${cx * S}" y="${y * S}"/>`);
    }
    cx += 6;
  }
  return `<g class="${cls}">${out.join('')}</g>`;
}
const width5 = (str) => str.length * 6 - 1;
function defineFont5() {
  for (const ch of used5) {
    const g = bitmap(FONT5[ch].split('|'), 1, (c) => c === '#');
    const kl = ring(g, [[2, 1], [1, 2], [2, 2]]);
    defs.push(`<symbol id="f${ch.codePointAt(0)}" overflow="visible"><path fill="#000" d="${pathOf(kl)}"/><path d="${pathOf(g)}"/></symbol>`);
  }
}

