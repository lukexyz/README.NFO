function teeth(letter) {
  const top = BODY[letter][0];
  const w = top.length;
  const row = [...'.'.repeat(w)];
  for (let x = 0; x < w; x++) {
    if (top[x] !== '#') continue;
    if (letter === 'W' || letter === 'Y') {
      const s = x === 0 || top[x - 1] !== '#';
      const e = x === w - 1 || top[x + 1] !== '#';
      if (s || e) row[x] = '#';
    } else if (x % 4 === 1 || x % 4 === 2) row[x] = '#';
  }
  const r = row.join('');
  return [r, r];
}

