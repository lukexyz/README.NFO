// "Vertical copper bars" README banner for CASTAWAY.
//
//   node examples/castaway/src/15-kefrens-bars_opus_5.5.mjs
//   node examples/castaway/src/15-kefrens-bars_opus_5.5.mjs --at=7.5 --out=some/where.svg
//
// Regenerates ../assets/15-kefrens-bars_opus_5.5.svg. Plain Node, no deps,
// deterministic (no clock, no Math.random). --at bakes a head start (seconds)
// into every animation delay so late frames can be checked without waiting;
// use it only together with --out, never in place.
//
// The style: the Amiga "Kefrens bars" / "Alcatraz bars" effect (c. 1989-91).
// The hardware trick was to show ONE line of video memory on every scanline
// and to draw one more shaded vertical bar into that line each time the beam
// moved down. A bar drawn at scanline k therefore shows on every line from k
// to the bottom, later bars cover earlier ones, the top of the screen is
// sparse and the bottom is a woven wall, and because each new bar sits on a
// sine of k the pile braids into ribbons. Nothing here is copied from any
// production: the letters, palette, sprites and copy are drawn for this file.
//
// How the SVG does it (the real mechanism, not a picture of it)
//   * For every virtual scanline k and every ribbon r there is one bar that
//     starts at row k and runs off the bottom. Paint order is k ascending, so
//     later bars cover earlier ones exactly as the beam did.
//   * Its X is the sum of two sines. Each sine is ONE shared @keyframes track,
//     pre-quantised to whole virtual pixels and played with step-end timing,
//     so a bar only ever moves by a whole (3 px) Amiga pixel. Rows differ only
//     in animation-delay (a class per phase), which is the "phase per
//     scanline" of the original. Outer <g> = slow swing, inner <use> = twist,
//     and the twist runs up the screen while the swing runs down.
//   * The bar shading is one 12-bit ramp per ribbon (hard-stop gradient,
//     objectBoundingBox), so all 304 bars share three gradients. The sea
//     ribbon starts on the top line, the sun a quarter of the way down and
//     the coral half way, so the top is sparse round the title.
//   * Swing period 12 s, twist period 6 s: four and two bars of the theme
//     (80 BPM, 3 s a bar), so the whole braid loops every 12 s.
//   * The title is rasterised here, pixel by pixel, into sandcastle bricks;
//     the scroller is 7x8 glyph symbols placed with <use>, moving one whole
//     pixel per step. She sits in the crook of the Y and nods on every beat.
//   * prefers-reduced-motion pauses every track where it starts (a full
//     braid, not a collapsed column), so the scroller, beat lights and her
//     head simply hold still on a complete frame.
// (The .md beside the assets is hand-written, not generated by this script.)

