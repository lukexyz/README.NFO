// ------------------------------------------------------------------ pixels
// A pixel set is a Set of "x,y" strings in virtual px.
const key = (x, y) => `${x},${y}`;
const unkey = (k) => k.split(',').map(Number);
// Merge pixels into horizontal runs, stack identical runs into rects, and
// emit one path (real px). ox/oy offset in virtual px.
function pathOf(set, ox = 0, oy = 0) {
  const rows = new Map();
  for (const k of set) {
    const [x, y] = unkey(k);
    if (!rows.has(y)) rows.set(y, []);
    rows.get(y).push(x);
  }
  const runs = [];
  for (const [y, xs] of rows) {
    xs.sort((a, b) => a - b);
    let s = xs[0];
    let p = xs[0];
    for (let i = 1; i <= xs.length; i++) {
      if (i < xs.length && xs[i] === p + 1) { p = xs[i]; continue; }
      runs.push([s, p + 1, y]);
      if (i < xs.length) { s = xs[i]; p = xs[i]; }
    }
  }
  runs.sort((a, b) => a[2] - b[2] || a[0] - b[0]);
  const live = new Set(runs.map((r) => `${r[0]},${r[1]},${r[2]}`));
  const out = [];
  for (const r of runs) {
    const k0 = `${r[0]},${r[1]},${r[2]}`;
    if (!live.has(k0)) continue;
    live.delete(k0);
    let h = 1;
    while (live.has(`${r[0]},${r[1]},${r[2] + h}`)) { live.delete(`${r[0]},${r[1]},${r[2] + h}`); h++; }
    out.push(`M${(ox + r[0]) * S} ${(oy + r[2]) * S}h${(r[1] - r[0]) * S}v${h * S}h${-(r[1] - r[0]) * S}z`);
  }
  return out.join('');
}
// Pixels around `set` (8-neighbour ring), plus optional extra offsets.
function ring(set, extra = []) {
  const out = new Set();
  const offs = [];
  for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) offs.push([dx, dy]);
  offs.push(...extra);
  for (const k of set) {
    const [x, y] = unkey(k);
    for (const [dx, dy] of offs) {
      const k2 = key(x + dx, y + dy);
      if (!set.has(k2)) out.add(k2);
    }
  }
  return out;
}
// Parse a bitmap ('#' or colour letters) at `cell` virtual px per cell.
function bitmap(rows, cell = 1, lit = (c) => c !== '.') {
  const set = new Set();
  rows.forEach((row, y) => [...row].forEach((c, x) => {
    if (!lit(c)) return;
    for (let dy = 0; dy < cell; dy++) for (let dx = 0; dx < cell; dx++) set.add(key(x * cell + dx, y * cell + dy));
  }));
  return set;
}

// ------------------------------------------------------------------ palette
// Amiga OCS: 12-bit colour, ramps of 7 steps from a near-black edge to a
// bright centre. Three sunny hues from the island: the shallow sea, the
// midday sun and her coral tank top. (Always daytime: the black is the
// screen, not the sky.)
const RAMPS = {
  sea: ['#012', '#024', '#047', '#079', '#0ab', '#4cd', '#9ee', '#eff'],
  sun: ['#110', '#420', '#740', '#a70', '#da1', '#fc3', '#fe7', '#ffd'],
  coral: ['#200', '#511', '#833', '#b44', '#e66', '#f98', '#fcb', '#fed'],
};
const BW = 14; // bar width, virtual px
function barGradient(id, ramp) {
  // columns 0 1 2 3 4 5 7 7 5 4 3 2 1 0: dark edges, hot centre, each a flat
  // 12-bit colour (hard-stop pairs)
  const st = [];
  for (let i = 0; i < BW; i++) {
    const d = Math.min(i, BW - 1 - i);
    const c = hex(ramp[d >= 6 ? 7 : d]);
    st.push(`<stop offset="${n(i / BW, 4)}" stop-color="${c}"/><stop offset="${n((i + 1) / BW, 4)}" stop-color="${c}"/>`);
  }
  defs.push(`<linearGradient id="${id}">${st.join('')}</linearGradient>`);
}

// ------------------------------------------------------------------ bars
const T1 = 4 * BAR;   // swing period: 12 s
const T2 = 2 * BAR;   // twist period: 6 s
const A1 = 116;       // swing amplitude (virtual px)
const A2 = 28;        // twist amplitude
const P1 = 96;        // scanlines per swing cycle
const P2 = 60;        // scanlines per twist cycle
// Ribbons join the pile at different scanlines: the sea from the top line,
// the sun a quarter of the way down, her coral half way. So the top of the
// screen is one lone ribbon round the title and the bottom is all three.
const RIBBONS = [['sea', 0], ['sun', 34], ['coral', 70]];
const NR = RIBBONS.length;
const CX = Math.round(VW / 2 - BW / 2);
RIBBONS.forEach(([hue], r) => {
  barGradient(`g${hue}`, RAMPS[hue]);
  defs.push(`<rect id="r${r}" x="${CX * S}" width="${BW * S}" height="${H}" fill="url(#g${hue})"/>`);
});

// One quantised sine track: a keyframe only where the rounded value changes.
function track(name, A, T) {
  const N = 6000;
  const frames = [];
  let last = null;
  for (let i = 0; i < N; i++) {
    const v = Math.round(A * Math.sin((2 * Math.PI * i) / N));
    if (v !== last) {
      frames.push(`${n((i / N) * 100, 3)}%{transform:translateX(${v * S}px)}`);
      last = v;
    }
  }
  frames.push('100%{transform:translateX(0)}');
  css.push(`@keyframes ${name}{${frames.join('')}}.${name}{animation:${name} ${T}s step-end infinite}`);
}
track('A', A1, T1);
track('B', A2, T2);
for (let i = 0; i < P1; i++) css.push(`.a${i}{animation-delay:${dly((-T1 * i) / P1)}}`);
for (let i = 0; i < P2; i++) css.push(`.b${i}{animation-delay:${dly((-T2 * i) / P2)}}`);

const bars = [];
for (let k = 0; k < VH; k++) {
  for (let r = 0; r < NR; r++) {
    if (k < RIBBONS[r][1]) continue;
    const i1 = (((k + Math.round((r * P1) / NR)) % P1) + P1) % P1;
    const i2 = (((-k + Math.round((r * P2) / NR)) % P2) + P2) % P2;
    bars.push(`<g class="A a${i1}"><use class="B b${i2}" href="#r${r}" y="${k * S}"/></g>`);
  }
}

// The same trick in text, for the README's details block: one line buffer,
// one more bar per ribbon written into it per printed row, and every row
// printed is the whole buffer so far. `--ascii` prints it and exits.
function asciiBars() {
  const COLS = 76;
  const ROWS = 18;
  const BAR_TXT = '░▒▓█▓▒░';
  const line = [...' '.repeat(COLS)];
  const out = [];
  for (let k = 0; k < ROWS; k++) {
    for (const ph of [0, Math.PI]) {
      const x = Math.round(COLS / 2 - 3.5 + 28 * Math.sin((2 * Math.PI * k) / 34 + ph + 0.3) + 4 * Math.sin((-2 * Math.PI * k) / 11 + 1));
      [...BAR_TXT].forEach((c, i) => { if (x + i >= 0 && x + i < COLS) line[x + i] = c; });
    }
    out.push(line.join('').replace(/\s+$/, ''));
  }
  return out.join('\n');
}
if (process.argv.includes('--ascii')) {
  console.log(asciiBars());
  process.exit(0);
}

