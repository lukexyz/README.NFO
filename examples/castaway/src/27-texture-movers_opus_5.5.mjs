const hex = (a) => '#' + a.map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('');
function ramp(stops, p) {
  for (let i = 0; i < stops.length - 1; i++) {
    const [p0, c0] = stops[i];
    const [p1, c1] = stops[i + 1];
    if (p <= p1 || i === stops.length - 2) {
      const t = Math.max(0, Math.min(1, (p - p0) / (p1 - p0)));
      const a = rgb(c0);
      const b = rgb(c1);
      return hex(a.map((v, k) => v + (b[k] - v) * t));
    }
  }
  return stops[stops.length - 1][1];
}

// ------------------------------------------------------------------ pixels
// Cells are [x, y] in art pixels. Merge into horizontal runs, stack equal
// runs into rects, emit one path in real px (scale S, offset ox/oy real px).
function cellsPath(cells, S, ox = 0, oy = 0) {
  const rows = new Map();
  for (const [x, y] of cells) {
    if (!rows.has(y)) rows.set(y, new Set());
    rows.get(y).add(x);
  }
  const runs = [];
  for (const [y, set] of rows) {
    const xs = [...set].sort((a, b) => a - b);
    let s = xs[0];
    let p = xs[0];
    for (let i = 1; i <= xs.length; i++) {
      if (i < xs.length && xs[i] === p + 1) { p = xs[i]; continue; }
      runs.push([s, p + 1, y]);
      if (i < xs.length) { s = xs[i]; p = xs[i]; }
    }
  }
  runs.sort((a, b) => a[2] - b[2] || a[0] - b[0]);
  const live = new Set(runs.map((r) => r.join(',')));
  let d = '';
  for (const r of runs) {
    const k0 = r.join(',');
    if (!live.has(k0)) continue;
    live.delete(k0);
    let h = 1;
    while (live.has(`${r[0]},${r[1]},${r[2] + h}`)) { live.delete(`${r[0]},${r[1]},${r[2] + h}`); h++; }
    const w = (r[1] - r[0]) * S;
    d += `M${n(ox + r[0] * S)} ${n(oy + r[2] * S)}h${n(w)}v${n(h * S)}h${n(-w)}z`;
  }
  return d;
}
// A little paint box: set(x, y, colour), then paths() groups by colour.
class Canvas {
  constructor() { this.m = new Map(); }
  set(x, y, c) { this.m.set(`${x},${y}`, [x, y, c]); }
  get(x, y) { const v = this.m.get(`${x},${y}`); return v ? v[2] : null; }
  del(x, y) { this.m.delete(`${x},${y}`); }
  paths(S, ox = 0, oy = 0, extra = '') {
    const by = new Map();
    for (const [x, y, c] of this.m.values()) {
      if (!by.has(c)) by.set(c, []);
      by.get(c).push([x, y]);
    }
    let out = '';
    for (const [c, cells] of by) out += `<path${extra} fill="${c}" d="${cellsPath(cells, S, ox, oy)}"/>`;
    return out;
  }
}
