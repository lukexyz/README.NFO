function logoSVG(word, x0, y0, sub) {
  const lit = new Set();
  const k = (x, y) => `${x},${y}`;
  [...word].forEach((ch, i) => {
    const ox = i * 18;                       // 16 sub-pixels + 2 gap
    LOGO[ch].forEach((row, y) => [...row].forEach((c, x) => {
      if (c !== '#') return;
      for (let dy = 0; dy < 2; dy++) for (let dx = 0; dx < 2; dx++) lit.add(k(ox + x * 2 + dx, y * 2 + dy));
    }));
  });
  const has = (x, y) => lit.has(k(x, y));
  // round every convex outer corner by one sub-pixel
  const cut = [];
  for (const key of lit) {
    const [x, y] = key.split(',').map(Number);
    for (const [ax, ay] of [[-1, -1], [1, -1], [-1, 1], [1, 1]]) {
      if (!has(x + ax, y) && !has(x, y + ay) && !has(x + ax, y + ay)) { cut.push(key); break; }
    }
  }
  cut.forEach((c) => lit.delete(c));
  const cells = [...lit].map((s) => s.split(',').map(Number));
  // outline = 8-neighbour ring
  const ring = new Set();
  for (const [x, y] of cells) {
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) if (!has(x + dx, y + dy)) ring.add(k(x + dx, y + dy));
  }
  const ringCells = [...ring].map((s) => s.split(',').map(Number));
  const body = [...cells, ...ringCells];
  const cv = new Canvas();
  const BANDS = ['#fff3d6', '#fff3d6', '#fff3d6', '#ffe7ad', '#ffe7ad', '#ffe7ad', '#ffd685', '#ffd685', '#ffd685', '#ffc070',
    '#ffc070', '#ffa865', '#ffa865', '#ff9262', '#ff9262', '#fb7d5e', '#fb7d5e', '#f06a59', '#f06a59', '#f06a59'];
  for (const [x, y] of cells) {
    let c = BANDS[y] || BANDS[19];
    if (!has(x, y - 1)) c = '#fffdf6';
    else if (!has(x, y + 1)) c = '#a83f3a';
    else if (!has(x - 1, y)) c = '#fff0cc';
    else if (!has(x + 1, y)) c = '#c9544a';
    cv.set(x, y, c);
  }
  return `<path fill="#000" opacity=".5" d="${cellsPath(body, sub, x0 + 2 * sub, y0 + 2 * sub)}"/>`
    + `<path fill="${INK}" d="${cellsPath(ringCells, sub, x0, y0)}"/>`
    + `<path fill="#ffc583" d="${cellsPath(cells, sub, x0, y0)}"/>`     // underlay: no seams between bands
    + cv.paths(sub, x0, y0);
}

