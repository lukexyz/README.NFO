// "Texture movers: rotozoomer and tunnel" README header for CASTAWAY.
//
//   node examples/castaway/src/27-texture-movers_opus_5.5.mjs
//   node examples/castaway/src/27-texture-movers_opus_5.5.mjs --at=7.5 --out=some/dir
//
// Regenerates, next to this folder:
//   ../assets/27-texture-movers_opus_5.5.svg           the tunnel banner
//   ../assets/27-texture-movers_opus_5.5-rotozoom.svg  the run-it band
// Plain Node, no deps, deterministic (no clock, no Math.random). --at bakes a
// head start (seconds) into every animation delay so late frames can be
// checked without waiting; use it only together with --out, never in place.
// (The .md beside the assets is hand-written, not generated by this script.)
//
// The style: the two "texture mover" effects of mid-90s PC intros. A tunnel
// flies you down an endless tube by shifting lookups into a wall texture; a
// rotozoomer spins and breathes one small tile repeated to infinity. Both sat
// behind a logo, with the text on a solid panel. Nothing here is copied from
// any production: the tile, letters, palette, sprites and copy are drawn for
// this file.
//
// How the SVG does it
//   TUNNEL. A per-pixel texture-mapped tunnel needs lookups an SVG cannot do,
//   so the wall is built from 16 rings instead, each a checkered annulus whose
//   inner radius is its outer radius / q. All 16 share ONE @keyframes track
//   (scale grows x16 over the ring's life, exponential, sampled at 48 points)
//   and differ only in animation-delay, so at any moment they sit at radii
//   r, rq, rq^2 ... and tile the wall with no gaps: an exponential zoom loops
//   with no seam. Timing is the theme's: one ring per beat (80 BPM), the wall
//   doubles in size every bar (3 s), a ring lives 4 bars.
//     * Twist: the same track turns each ring 90 degrees over its life, so
//       neighbours sit half a checker cell apart and the wall spirals.
//     * Depth fog: the track also animates `color`, and the ring symbol is
//       painted in currentColor, so far rings are dark and near rings bright.
//     * Wandering vanishing point: the track pushes each ring sideways by
//       D * (1 - smoothstep(depth)), so the far end sits D off-centre and the
//       near walls stay put. The whole tube then rolls (10 degrees a second),
//       which swings that bend round: the far end circles once every 36 s.
//     * The far end is not dark: it opens onto the island, in daylight, kept
//       upright by a counter-rotation. She nods on every beat.
//     * Every bar a sign flies out of the island along the tube (four slots,
//       three gags each, swapped while a slot is tiny), and a coconut with a
//       hermit crab inside walks the top of the logo in eighth-note steps.
//   ROTOZOOMER. One 48 px embossed sand tile (a C with a palm in it) as a
//   <pattern> on a huge rect, under three nested CSS animations: rotate
//   (10 degrees a second), zoom (breathing x0.75 to x1.45 every 4 bars) and a
//   slow drift of the texture centre. The run command sits on a solid plate.
//   Everything loops every 36 s (12 bars). prefers-reduced-motion pauses every
//   track at its first frame, which is already a complete picture.

