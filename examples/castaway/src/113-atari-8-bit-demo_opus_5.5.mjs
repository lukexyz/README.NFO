// "Atari 8-bit demo screen" README banner for CASTAWAY.
//
//   node examples/castaway/src/113-atari-8-bit-demo_opus_5.5.mjs
//   node examples/castaway/src/113-atari-8-bit-demo_opus_5.5.mjs --at=7.5 --out=some/where.svg
//   node examples/castaway/src/113-atari-8-bit-demo_opus_5.5.mjs --sheet=some/where.svg
//
// Regenerates ../assets/113-atari-8-bit-demo_opus_5.5.svg. Plain Node, no
// deps, deterministic (no clock, no Math.random). --at bakes a head start (in
// seconds) into every animation so later frames can be checked without
// waiting; use it only together with --out, never in place. --sheet writes a
// big contact sheet of the sprites and the 8x8 font, for pixel work.
//
// The style: an Atari 8-bit (800XL / 130XE) demo screen, catalogue entry
// demo-09. The machine builds its picture from a display list, one mode per
// row, and can fire an interrupt on any row to change the colour registers.
// The GTIA chip adds a mode only 80 pixels across (each pixel four hi-res
// pixels wide and one scanline tall) that shows sixteen brightness steps of
// ONE hue; the hue is whatever the register says on that scanline. So demo
// screens are soft, shaded, brick-like pictures whose tint changes band by
// band down the screen, with text rows and four-colour rows stacked in
// between, and small single-colour sprites (players and missiles) on top.
// Credited references, nothing copied: the hardware documentation on
// Wikipedia, and the Polish-centred scene's screens as described on Pouet and
// Demozoo. No group's logo, font, picture or words are reproduced; the letters,
// the 8x8 font, the island and the sprites are all drawn here.
//
// How the SVG does it (the real mechanism, not a picture of it)
//   * Units: x in hi-res pixels (352 across, the wide playfield), y in
//     scanlines (192 of them, the standard Atari screen). The viewBox adds an
//     8-unit border, so the frame is 368 x 208, close to 16:9.
//   * Palette: 16 hues x 16 luminances, built here in OKLCH (hue 0 is grey,
//     hues 1-15 go round the wheel 24 degrees apart). Every filled colour in
//     the picture is one of those 256.
//   * LOGO band (16-shade mode): the letters are a 0-15 luminance map on the
//     80-pixel grid, shaded by a little emboss (distance field -> normal ->
//     light from the top left). Each scanline is one <g>; inside it, one path
//     per luminance. The hue is not in the picture at all: one CSS keyframe
//     track per luminance walks round the hue wheel, and each scanline's
//     track is delayed by one step per line, so the hue bands roll up through
//     the letters like a per-scanline colour kernel, while the picture itself
//     never moves. That is the whole effect, and the whole joke.
//   * ISLAND band (16-shade mode + split colours + sprites): sky and sea are
//     pure per-scanline gradients whose hue steps every few lines, a sun of
//     luminance rings, clouds that drift by hardware-style fine scroll (two
//     hi-res pixels a step), an island, palm and raft in the same wide
//     pixels, sea glints that twinkle one beat in four and foam that swaps on
//     the half bar. She, the cat, the coconut crab and the bottle are drawn
//     like players: two-unit pixels laid over the picture, moved on the beat.
//   * TEXT rows (40-column mode, here 44 on the wide playfield): an 8x8 font
//     drawn for this file. In that mode the letters take the row's hue and
//     only choose a brightness, so each row is one hue; a stack of one-line
//     rects behind a clip of the glyphs scrolls up a line at a time, which is
//     the raster rolling through the text. The rows under the island use the
//     ten-line text mode (mode 3), so descenders clear the next row.
//   * TIMELINE row (four-colour mode, two-unit pixels): the real seed-1992
//     ten-hour run of activities.toml as of 2026-10-01, one pixel per 24
//     seconds, regular / occasional / rare in the three playfield colours and
//     the one super-rare event as a missile. Her activities are blocks as
//     long as they last; other lanes (cat, sea and sky, shore) are ticks. It
//     scrolls past under a NOW player, ten hours in four minutes, and wraps
//     without a seam.
//   * prefers-reduced-motion pauses every track where it starts, which is a
//     complete frame. Nothing flashes: each hue step keeps its brightness,
//     each logo line changes hue once per 0.8 s, and the sprites move on
//     the beat.
// (The .md beside the assets is hand-written, not generated by this script.)

