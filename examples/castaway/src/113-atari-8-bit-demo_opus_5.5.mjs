const GLYPH = new Map();
function glyph(ch) {
  if (GLYPH.has(ch)) return GLYPH.get(ch);
  const rows = FONT[ch];
  if (!rows) throw new Error(`no glyph for "${ch}"`);
  const grid = rows.map((r) => [...r].map((c) => (c === '#' ? 'x' : null)));
  const d = gridPaths(grid, 1, 0, 0).get('x');
  const id = `g${GLYPH.size.toString(36)}`;
  GLYPH.set(ch, d ? id : null);
  if (d) defs.push(`<path id="${id}" d="${d}"/>`);
  return d ? id : null;
}

// One 40-column text row: plain dark hue behind, letters of the same hue whose
// brightness is set per scanline by a rolling table (the raster in the text).
let textRowCount = 0;
// lines: 8 for mode 2, 10 for mode 3 (two more lines of background under it).
function textRow(y, str, { hue, bg, lums, dur = BAR, col0 = null, align = 'center', lines = 8 }) {
  if ([...str].length > 44) throw new Error(`text row too long (${[...str].length}): ${str}`);
  const id = `t${textRowCount++}`;
  const len = [...str].length;
  const c0 = col0 ?? (align === 'center' ? Math.floor((44 - len) / 2) : 1);
  const uses = [];
  [...str].forEach((ch, i) => {
    const g = glyph(ch);
    if (g) uses.push(`<use href="#${g}" x="${BX + (c0 + i) * 8}" y="${BY + y}"/>`);
  });
  defs.push(`<clipPath id="${id}">${uses.join('')}</clipPath>`);
  const P = lums.length;
  const rects = [];
  for (let i = 0; i < 8 + P; i++) {
    rects.push(`<rect x="${BX}" y="${BY + y + i}" width="${SW}" height="1" fill="${col(hue, lums[i % P])}"/>`);
  }
  css.push(`@keyframes r${id}{from{transform:translateY(0)}to{transform:translateY(-${P}px)}}`);
  const bgRect = bg == null ? '' : `<rect x="${BX}" y="${BY + y}" width="${SW}" height="${lines}" fill="${col(hue, bg)}"/>`;
  body.push(`${bgRect}<g clip-path="url(#${id})"><g style="animation:r${id} ${dur}s steps(${P}) infinite;animation-delay:${dly(0)}">${rects.join('')}</g></g>`);
  return { c0, len };
}

// ================================================================== LOGO
// CASTAWAY in a blocky face built for the 80-pixel grid: three-pixel stems,
// rounded outer corners, two-pixel counters. Each letter is an inside(x, y)
// test in display units (x in hi-res pixels, y in scanlines).
const LH = 32; // letter height, scanlines
function rr(x, y, x0, y0, x1, y1, r = {}) {
  if (x < x0 || x >= x1 || y < y0 || y >= y1) return false;
  const corner = (cx, cy, rad) => (rad ? (x - cx) ** 2 + (y - cy) ** 2 <= rad * rad : true);
  if (r.tl && x < x0 + r.tl && y < y0 + r.tl) return corner(x0 + r.tl, y0 + r.tl, r.tl);
  if (r.tr && x > x1 - r.tr && y < y0 + r.tr) return corner(x1 - r.tr, y0 + r.tr, r.tr);
  if (r.bl && x < x0 + r.bl && y > y1 - r.bl) return corner(x0 + r.bl, y1 - r.bl, r.bl);
  if (r.br && x > x1 - r.br && y > y1 - r.br) return corner(x1 - r.br, y1 - r.br, r.br);
  return true;
}
