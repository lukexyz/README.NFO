// '!' marks an event outside her lane. Returns [bar, bars, other].
function parseRun(s) {
  return s.split(',').map((e) => {
    const other = e.startsWith('!');
    const [a, b] = e.replace('!', '').split(':').map((v) => parseInt(v, 36));
    return [a, b, other];
  });
}
function timelineSvg() {
  const Y = BY + DL.timeline;
  const SEC_PER_PX = 24; // one four-colour pixel (2 units) per 24 seconds
  const RUN_S = 36000;
  const WPX = RUN_S / SEC_PER_PX; // 1500 pixels = 3000 units
  const W = WPX * 2;
  const tierCol = {
    regular: col(H.CYAN, 10),
    chained: col(H.CYAN, 10),
    occasional: col(H.AMBER, 12),
    rare: col(H.PINK, 10),
  };
  const BAK = col(H.BLUE, 1);
  const parts = [];
  // Idle track and hour marks. Four-colour mode allows background plus three
  // playfield colours per line, so: line 5 is the idle track (the background
  // register changed for that one line), lines 0-6 carry the three tier
  // colours, and line 7 has only the hour notches, the 0:00:00 one (where
  // the run wraps) brighter and wider.
  parts.push(`<rect x="0" y="5" width="${W}" height="1" fill="${col(H.BLUE, 4)}"/>`);
  for (let hr = 0; hr < 10; hr++) {
    const x = (hr * 3600) / SEC_PER_PX * 2;
    if (hr === 0) parts.push(`<rect x="${x - 2}" y="7" width="6" height="1" fill="${col(H.BLUE, 11)}"/>`);
    else parts.push(`<rect x="${x}" y="7" width="2" height="1" fill="${col(H.BLUE, 7)}"/>`);
  }
  // Her lane: a block as long as the activity, on lines 3-6. Everything
  // else (the cat, the sea and sky, the shore): a one-pixel tick on lines 0-1.
  const byColour = new Map();
  for (const tier of ['regular', 'chained', 'occasional', 'rare']) {
    for (const [bar, len, other] of parseRun(RUN[tier])) {
      const x0 = Math.floor((bar * 3) / SEC_PER_PX);
      const w = other ? 1 : Math.max(1, Math.round((len * 3) / SEC_PER_PX));
      const c = tierCol[tier];
      if (!byColour.has(c)) byColour.set(c, []);
      const rows = other ? [0, 2] : [3, 7];
      byColour.get(c).push(`M${x0 * 2} ${rows[0]}h${w * 2}v${rows[1] - rows[0]}h${-w * 2}z`);
    }
  }
  for (const [c, d] of byColour) parts.push(`<path fill="${c}" d="${d.join('')}"/>`);
  // Missile: the super-rare event, full height, one pixel wide.
  for (const [bar] of parseRun(RUN.super_rare)) {
    const x0 = Math.floor((bar * 3) / SEC_PER_PX) * 2;
    parts.push(`<rect x="${x0}" y="0" width="2" height="8" fill="${PCOL.m}"/>`);
  }
  defs.push(`<g id="tl">${parts.join('')}</g>`);
  defs.push(`<clipPath id="tlc"><rect x="${BX}" y="${Y}" width="${SW}" height="8"/></clipPath>`);
  const TL_T = 80 * BAR; // four minutes for the ten hours
  css.push(`@keyframes tl{from{transform:translateX(0)}to{transform:translateX(-${W}px)}}`);
  body.push(`<rect x="${BX}" y="${Y}" width="${SW}" height="8" fill="${BAK}"/>`);
  const NOW = 64; // the NOW player's column, units from the left
  body.push(`<g clip-path="url(#tlc)"><g transform="translate(${BX + NOW} ${Y})"><g style="animation:tl ${TL_T}s steps(${WPX}) infinite;animation-delay:${dly(0)}"><use href="#tl"/><use href="#tl" x="${W}"/><use href="#tl" x="${-W}"/></g></g></g>`);
  // NOW: a player drawn as an I-beam, eight lines tall, inside the row.
  body.push(`<path fill="${col(H.SAND, 15)}" d="M${BX + NOW - 2} ${Y}h6v1h-2v6h2v1h-6v-1h2v-6h-2z"/>`);
}

