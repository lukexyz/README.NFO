const nib = (v) => Math.max(0, Math.min(15, Math.round(v))).toString(16);
const c12 = (r, g, b) => `#${nib(r)}${nib(g)}${nib(b)}`;
const p12 = (s) => [...s.slice(1)].map((ch) => parseInt(ch, 16));
const mix = (a, b, t) => {
  const A = p12(a);
  const B = p12(b);
  return c12(...A.map((v, i) => v + (B[i] - v) * t));
};

