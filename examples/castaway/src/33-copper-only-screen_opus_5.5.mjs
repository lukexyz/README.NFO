const LW = 14, LH = 28;
function letterMask(ops) {
  const m = new Set();
  for (const op of ops) {
    const [kind, x, y, w = 1, h = 1] = op;
    for (let yy = y; yy < y + h; yy++) for (let xx = x; xx < x + w; xx++) {
      if (xx < 0 || yy < 0 || xx >= LW || yy >= LH) continue;
      if (kind === '+') m.add(key(xx, yy)); else m.delete(key(xx, yy));
    }
  }
  return m;
}
