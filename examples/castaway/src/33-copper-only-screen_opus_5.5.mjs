const usedGlyphs = new Set();
function glyphId(ch) {
  if (!FONT[ch]) throw new Error(`no glyph for "${ch}"`);
  usedGlyphs.add(ch);
  return `s${ch.codePointAt(0).toString(36)}`;
}
// <use> elements for a line of small text at virtual (x, y).
function text(str, x, y) {
  const out = [];
  [...str].forEach((ch, i) => {
    if (ch === ' ') return;
    out.push(`<use href="#${glyphId(ch)}" x="${x + i * ADV}" y="${y}"/>`);
  });
  return out.join('');
}
