  const outline = new Set([...ring(solid, false)].filter((k) => unkey(k)[1] < cutBelow));
  const parts = [`<path fill="${HER_COL.K}" d="${pathOf(outline)}"/>`];
  for (const [ch, set] of byCol) parts.push(`<path fill="${HER_COL[ch]}" d="${pathOf(set)}"/>`);
  return parts.join('');
