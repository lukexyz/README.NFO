// "Copper-only screen" README banner for CASTAWAY.
//
//   node examples/castaway/src/33-copper-only-screen_opus_5.5.mjs
//   node examples/castaway/src/33-copper-only-screen_opus_5.5.mjs --at=7.5 --out=some/where.svg
//   node examples/castaway/src/33-copper-only-screen_opus_5.5.mjs --sprite=some/where.svg
//
// Regenerates ../assets/33-copper-only-screen_opus_5.5.svg. Plain Node, no
// deps, deterministic (no clock, no Math.random). --at bakes a head start (in
// seconds) into every animation delay so later frames can be checked without
// waiting; use it only together with --out, never in place. --sprite writes a
// big contact sheet of her sprite and the title letters, for pixel work.
//
// The style: the Amiga "copper-only" screen of 1990 (catalogue entry c64-09).
// The copper is the co-processor that waits for the video beam to reach a
// position and then moves a value into a colour register. Do that on every
// scanline, and several times along each line, and you get a picture made of
// nothing but colour changes: no bitplanes at all. Colour can change on every
// line, but only every few pixels along a line, so the texture is wide and
// short. Each effect sits in its own window with a thin light frame. Copper
// Master (Angels) and Look! No bitplanes (Razor 1911), both October 1990, are
// the credited references; nothing of theirs is copied. The windows, palettes,
// letters, sprite and words here are all drawn and written for this file.
//
// How the SVG does it (the real mechanism, not a picture of it)
//   * Hero window, diagonal bands: 39 columns, each 8 px wide (one copper
//     MOVE along a line), filled with ONE hard-stop gradient of 64 colours
//     (four triangular 16-step ramps: palm green, sand, sea, foam), two
//     scanlines per colour. Each column is offset 4 scanlines from its
//     neighbour, which is what makes the bands diagonal. The whole group then
//     rolls down one scanline per step, 128 steps in 12 s (four bars of the
//     theme at 80 BPM).
//   * SUN window, the diamond: every 8 px x 1 line cell gets a level
//     4 * |column| + |line| from the centre. Cells of one level share a class
//     and the class cycles through a 32-colour palette (step-end), each level
//     one step behind the last, so the rings pulse outward: palette cycling,
//     6 s per cycle, no script.
//   * ISLAND window: a copper sky (one colour per line), a sea of cyan lines
//     whose phase is 1/distance from the horizon so the waves come in with
//     perspective, a sand mound whose edges move only in 4 px steps (the
//     copper's horizontal resolution), and a twisted ribbon for a palm trunk:
//     one rect per line, swayed and twisted by two shared keyframe tracks
//     with a per-line delay, red-tan and grey stripes over the cyan lines.
//   * LANES window, the plaid: vertical bars shaded in chunky 4 px steps,
//     horizontal bars shaded per scanline, sliding in opposite directions;
//     the upper group uses mix-blend-mode:screen so red and green cross to
//     yellow, red and blue to magenta, green and blue to cyan.
//   * The title is eight 16 px wide sprites, one letter each (the Amiga has
//     exactly eight hardware sprites, and CASTAWAY has exactly eight
//     letters), three colours each, recoloured per scanline. She is one more
//     sprite pair further down, nodding once per beat.
//   * prefers-reduced-motion pauses every track where it starts, which is a
//     complete frame: all four effects, the title and every line of text.
//   * Slowest flicker rule: no area changes colour faster than one ramp step
//     per 0.09 s, and every ramp is smooth, so nothing flashes.
// (The .md beside the assets is hand-written, not generated by this script.)

