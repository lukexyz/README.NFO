// "Vector objects" README banner for CASTAWAY.
//
//   node examples/castaway/src/26-vector-objects_opus_5.5.mjs
//   node examples/castaway/src/26-vector-objects_opus_5.5.mjs --at=9.4 --out=some/where.svg
//
// Regenerates ../assets/26-vector-objects_opus_5.5.svg (the banner) and
// ../assets/26-vector-objects_opus_5.5-props.svg (a strip of wireframe props
// for the .md's details block). Plain Node, no deps, deterministic (no clock,
// no Math.random). --at bakes a head start (seconds) into every animation so
// a late frame can be checked without waiting; use it only with --out.
// (The .md beside the assets is hand-written, not generated by this script.)
//
// The style: the demo/cracktro "vector object" family (glenz, dot scroller,
// vector balls, wireframe). One translucent object turns slowly in the middle
// of a plain field while the text does the talking. Nothing here is copied
// from any production: the object, fonts, palette, copy and crew are made up
// in this file.
//
// How the SVG does it
//   * GLENZ. A tetrakis hexahedron (a cube with a low pyramid on every face,
//     24 triangles, two-coloured like a chessboard) is rotated here on three
//     axes and projected with perspective, F frames per turn. Every face is
//     one <polygon> whose points and fill are SMIL value lists; the browser
//     interpolates between frames. Faces are 46 (white) and 74 (coral pink)
//     percent opaque, so the back of the object shows through the front and
//     overlaps get brighter. No depth sort needed: the point of glenz.
//   * DOT SCROLLER. A ring of N character slots round the object's equator,
//     tilted towards the viewer. Every slot shares ONE @keyframes (a full
//     turn: translate on the ellipse, scaleX = cos, skewY for the slope, and
//     the brightness) and differs only in animation-delay. The ring is drawn
//     twice: the far half behind the glenz (dim, mirrored, seen through the
//     glass) and the near half in front. A slot holds R glyphs, one per turn,
//     and swaps glyph while it is directly behind the object, so N*R
//     characters of text go round on N slots.
//   * VECTOR BALLS. The title is a 5x7 matrix of shaded balls (one radial
//     gradient, one <use> each). The columns float on a slow wave, and once
//     a minute, on the bar, the letters flip one after another: a per-ball
//     CSS variable (its distance from the letter's axis) feeds one shared
//     @keyframes, so the balls swing round in 3D with depth scaling.
//   * TEXT WRITER. Five pages, hard cuts between them (the project's own
//     motion default). Page 1 is already typed at t = 0. Typing is a cover
//     cut from the field's own gradient stepping off one character at a time,
//     with the cursor riding its edge.
//   * Every period divides 60 s, the length of the project's theme (20 bars
//     of 3 s at 80 BPM): the glenz cycles every 30 s, the ring every 15 s, the
//     object dips on every beat, a ripple leaves it on every bar, and the
//     title flip starts on bar 4.
//   * prefers-reduced-motion pauses every CSS track where it starts and swaps
//     the SMIL glenz for a still copy of its first frame.

