// solid pixel glyphs: one path per glyph, runs merged per row
const usedPix = new Set();
function pixPath(ch) {
  let d = '';
  rows(ch).forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x++; continue; }
      let e = x;
      while (e < row.length && row[e] === '#') e++;
      d += `M${x} ${y}h${e - x}v1h${x - e}z`;
      x = e;
    }
  });
  return d;
}
// a line of pixel text as a group of <use>, unit u, top-left (x, y)
function pixLine(str, u) {
  let uses = '';
  [...str].forEach((ch, i) => {
    if (ch === ' ') return;
    rows(ch);
    usedPix.add(ch);
    uses += `<use href="#${gid(ch)}" x="${i * ADV}"/>`;
  });
  return uses;
}
const textW = (str, u) => ([...str].length * ADV - 1) * u;
let defsText = '';
let lineId = 0;
// shadowed pixel text: defined once, drawn twice (shadow, face)
function pixText(str, x, y, u, { anchor = 'start', fill = '#fff', shadow = INK, sh = 1, cls = '' } = {}) {
  const w = textW(str, u);
  const x0 = anchor === 'middle' ? x - w / 2 : anchor === 'end' ? x - w : x;
  const id = `t${lineId++}`;
  defsText += `<g id="${id}" transform="translate(${n(x0)} ${n(y)}) scale(${u})">${pixLine(str, u)}</g>`;
  const shadowUse = shadow ? `<use href="#${id}" x="${n(sh * u)}" y="${n(sh * u)}" fill="${shadow}"${typeof shadow === 'string' && shadow.length > 7 ? '' : ''}/>` : '';
  return { svg: `<g${cls ? ` class="${cls}"` : ''}>${shadowUse}<use href="#${id}" fill="${fill}"/></g>`, x0, w };
}

