// ================================================================== GLENZ
const OBJ = { cx: 232, cy: 200, S: 120, D: 5.2, P: 30, F: 48, Q: 2 };   // Q: coordinate steps per px
// tetrakis hexahedron: cube corners plus a pyramid apex over every face
const PYR = 0.62;            // apex height over the face (cube half-size 1)
const verts = [];
for (const x of [-1, 1]) for (const y of [-1, 1]) for (const z of [-1, 1]) verts.push([x, y, z]);
const vIndex = (v) => verts.findIndex((w) => w[0] === v[0] && w[1] === v[1] && w[2] === v[2]);
const faces = [];
for (let ax = 0; ax < 3; ax++) {
  for (const s of [-1, 1]) {
    const apex = [0, 0, 0];
    apex[ax] = s * (1 + PYR);
    verts.push(apex);
    const ai = verts.length - 1;
    const a1 = (ax + 1) % 3, a2 = (ax + 2) % 3;
    const ring = [[-1, -1], [1, -1], [1, 1], [-1, 1]].map(([p, q]) => {
      const v = [0, 0, 0];
      v[ax] = s; v[a1] = p; v[a2] = q;
      return vIndex(v);
    });
    for (let j = 0; j < 4; j++) {
      let f = [ring[j], ring[(j + 1) % 4], ai];
      // outward winding
      const [A, B, C] = f.map((i) => verts[i]);
      const nrm = cross(sub(B, A), sub(C, A));
      const cen = [0, 1, 2].map((k) => (A[k] + B[k] + C[k]) / 3);
      if (dot(nrm, cen) < 0) f = [f[0], f[2], f[1]];
      faces.push(f);
    }
  }
}
function sub(a, b) { return [a[0] - b[0], a[1] - b[1], a[2] - b[2]]; }
function cross(a, b) { return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]; }
function dot(a, b) { return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]; }
function norm(a) { const l = Math.hypot(...a); return a.map((v) => v / l); }
// normalise so the farthest vertex sits on the unit sphere
const RMAX = Math.max(...verts.map((v) => Math.hypot(...v)));
for (const v of verts) for (let k = 0; k < 3; k++) v[k] /= RMAX;
// chessboard colouring: BFS over faces sharing an edge
const edgeKey = (a, b) => (a < b ? `${a}-${b}` : `${b}-${a}`);
const byEdge = new Map();
faces.forEach((f, i) => { for (let j = 0; j < 3; j++) { const k = edgeKey(f[j], f[(j + 1) % 3]); if (!byEdge.has(k)) byEdge.set(k, []); byEdge.get(k).push(i); } });
const colour = new Array(faces.length).fill(-1);
colour[0] = 0;
const queue = [0];
while (queue.length) {
  const i = queue.shift();
  const f = faces[i];
  for (let j = 0; j < 3; j++) {
    for (const o of byEdge.get(edgeKey(f[j], f[(j + 1) % 3]))) {
      if (o === i) continue;
      if (colour[o] === -1) { colour[o] = 1 - colour[i]; queue.push(o); }
      else if (colour[o] === colour[i]) throw new Error('glenz mesh is not two-colourable');
    }
  }
}

function rotAt(u0) {
  // three axes, integer turns per period so the loop closes; frame 0 starts
  // a little way in, so the first (and the reduced-motion) frame looks 3D
  const u = u0 + 0.13;
  const b = TAU * 2 * u;             // spin
  const a = TAU * 1 * u + 0.55;      // tumble
  const g = 0.32 * Math.sin(TAU * u); // sway
  const ca = Math.cos(a), sa = Math.sin(a), cb = Math.cos(b), sb = Math.sin(b), cg = Math.cos(g), sg = Math.sin(g);
  return (v) => {
    // Ry(b)
    let x = v[0] * cb + v[2] * sb, y = v[1], z = -v[0] * sb + v[2] * cb;
    // Rx(a)
    const y2 = y * ca - z * sa, z2 = y * sa + z * ca;
    y = y2; z = z2;
    // Rz(g)
    const x3 = x * cg - y * sg, y3 = x * sg + y * cg;
    return [x3, y3, z];
  };
}
const LIGHT = norm([-0.5, -0.7, 0.55]);
const GZ = [
  { op: 0.46, lit: '#ffffff', dim: '#d6f0ff', back: '#7cc6f4' },   // glass
  { op: 0.74, lit: '#ffa6bd', dim: '#ff3f7a', back: '#b02a6c' },   // coral pink
];
const proj = (p) => {
  const k = OBJ.D / (OBJ.D - p[2]);
  return [Math.round(p[0] * OBJ.S * k * OBJ.Q), Math.round(p[1] * OBJ.S * k * OBJ.Q)];
};
const frames = [];
for (let fi = 0; fi < OBJ.F; fi++) {
  const R = rotAt(fi / OBJ.F);
  const rv = verts.map(R);
  const pv = rv.map(proj);
  frames.push(faces.map((f, i) => {
    const [A, B, C] = f.map((k) => rv[k]);
    const nr = norm(cross(sub(B, A), sub(C, A)));
    const cen = [0, 1, 2].map((k) => (A[k] + B[k] + C[k]) / 3);
    const toCam = norm(sub([0, 0, OBJ.D], cen));
    const facing = dot(nr, toCam);
    const pal = GZ[colour[i]];
    let fill;
    if (facing > 0) fill = lerpHex(pal.dim, pal.lit, Math.max(0, dot(nr, LIGHT)) ** 0.8);
    else fill = lerpHex(pal.back, pal.dim, 0.25 * Math.max(0, -dot(nr, LIGHT)));
    return { pts: f.map((k) => `${pv[k][0]},${pv[k][1]}`).join(' '), fill };
  }));
}
function glenzSvg() {
  let anim = '';
  let still = '';
  const begin = T0 ? ` begin="-${n(T0, 3)}s"` : '';
  faces.forEach((f, i) => {
    const pts = frames.map((fr) => fr[i].pts);
    const fills = frames.map((fr) => fr[i].fill);
    pts.push(pts[0]); fills.push(fills[0]);
    const op = GZ[colour[i]].op;
    anim += `<polygon fill-opacity="${op}" points="${pts[0]}"><animate attributeName="points" dur="${OBJ.P}s"${begin} repeatCount="indefinite" values="${pts.join(';')}"/><animate attributeName="fill" dur="${OBJ.P}s"${begin} repeatCount="indefinite" values="${fills.join(';')}"/></polygon>`;
    still += `<polygon fill-opacity="${op}" fill="${fills[0]}" points="${pts[0]}"/>`;
  });
  return `<g class="gz">${anim}</g><g class="gzs">${still}</g>`;
}

