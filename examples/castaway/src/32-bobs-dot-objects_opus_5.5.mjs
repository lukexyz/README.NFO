// Pre-drawn balls in six sizes, lit from the upper left, quantised to a
// 12-bit ramp with a white highlight. The far sizes are drawn darker.
const BLUE = ['#001', '#012', '#124', '#236', '#248', '#35a', '#46c', '#68e', '#9bf', '#cef', '#fff'];
const NUT = ['#100', '#210', '#320', '#421', '#531', '#642', '#753', '#864', '#a86', '#cb9', '#fed'];
