// the crown: three coconuts and eight fronds that arch and droop, each a
// spine of dots with leaflets hanging off both sides
const CRX = lean(TRUNK_H) * Math.sin(LEAN_A);
const CRZ = lean(TRUNK_H) * Math.cos(LEAN_A);
const FRONDS = 8;
const FROND_L = 33;
const GREENS = ['#3b4', '#4c4', '#5d5', '#6e5', '#8f6', '#bf8'];
const gAt = (u, dk = 0) => GREENS[Math.max(0, Math.min(GREENS.length - 1, Math.floor(u * GREENS.length) + dk))];
let seed = 1992;                     // the project's default seed
const rnd = () => {                  // mulberry32
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
for (let f = 0; f < FRONDS; f++) {
  const al0 = (f / FRONDS) * 2 * Math.PI + 0.35 + (rnd() - 0.5) * 0.5;
  const curl = (rnd() - 0.5) * 0.7;
  const len = FROND_L - rnd() * 9;
  const lift = 6 + rnd() * 8;
  const droop = lift + 11 + rnd() * 8;
  for (let s = 1.8, j = 0; s <= len; s += 1.8, j++) {
    const u = s / len;
    const al = al0 + curl * u * u;
    const h = TRUNK_H + lift * u - droop * u * u;
    const X = CRX + s * Math.sin(al0 + curl * u * u / 2);
    const Z = CRZ + s * Math.cos(al0 + curl * u * u / 2);
    dot(X, Z, h, gAt(u));
    if (u > 0.15 && u < 0.97 && j % 2 === 0) {
      const w = 2.4 * Math.sin(Math.PI * Math.min(1, u * 1.1));
      for (const side of [1, -1]) {
        dot(X + Math.cos(al) * side * w, Z - Math.sin(al) * side * w, h - 1.5 - u * 1.5, gAt(u, -1));
      }
    }
  }
}
