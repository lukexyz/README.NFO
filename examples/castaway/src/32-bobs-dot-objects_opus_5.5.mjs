const BRIGHT = [0.6, 0.7, 0.8, 0.88, 0.95, 1.0];
function ball(d, ramp, bright, fibre) {
  const groups = new Map();
  const c0 = (d - 1) / 2;
  const R = d / 2;
  const L = [-0.52, -0.62, 0.59];
  const ln = Math.hypot(...L);
  const top = ramp.length - 2;
  for (let py = 0; py < d; py++) {
    for (let px = 0; px < d; px++) {
      const dx = (px + 0.5 - R) / R;
      const dy = (py + 0.5 - R) / R;
      const rr = dx * dx + dy * dy;
      if (rr > 1.02) continue;
      const nz = Math.sqrt(Math.max(0, 1 - rr));
      const lam = Math.max(0, (dx * L[0] + dy * L[1] + nz * L[2]) / ln);
      let I = 0.16 + 0.84 * lam;
      // a little rim light from below right, the way bobs were hand-shaded
      if (dx + dy > 0.9 && rr > 0.55) I = Math.max(I, 0.3);
      let idx = Math.round(I * bright * top);
      if (fibre && idx > 2 && (px * 7 + py * 3) % 5 === 0) idx -= 2;   // husk
      const hx = dx + 0.42;
      const hy = dy + 0.46;
      let c = ramp[Math.max(0, Math.min(top, idx))];
      if (hx * hx + hy * hy < (d >= 11 ? 0.05 : 0.09)) c = bright > 0.8 ? ramp[top + 1] : ramp[top];
      const k = key(px - c0, py - c0);
      if (!groups.has(c)) groups.set(c, new Set());
      groups.get(c).add(k);
    }
  }
  return colourPaths(groups);
}
