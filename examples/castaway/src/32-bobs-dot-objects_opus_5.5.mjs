// "Bobs and dot objects" README banner for CASTAWAY.
//
//   node examples/castaway/src/32-bobs-dot-objects_opus_5.5.mjs
//   node examples/castaway/src/32-bobs-dot-objects_opus_5.5.mjs --at=21 --out=some/where.svg
//
// Regenerates ../assets/32-bobs-dot-objects_opus_5.5.svg. Plain Node, no
// deps, deterministic (no clock, no Math.random). --at bakes a head start
// (seconds) into every animation delay so late frames can be checked without
// waiting; use it only together with --out, never in place.
//
// The style: the early Amiga "bobs" and "dot object" screens (c. 1989-90).
// A black screen with one object made of many identical pieces: a chain of
// shaded blue balls snaking round a figure of eight, or a lattice of single
// dots turning in space, shut in above and below by a one-pixel rainbow rule,
// over a strip with a gradient-filled logo. Razor 1911's Liquid Bobs and
// Space Dots are the usual examples and are credited as the reference here;
// nothing of theirs is copied. The balls, dots, letters, palette, sprite and
// copy are drawn for this file.
//
// What this banner does with it
//   * Both effects at once: a dot object (a palm on a little island of dot
//     rings, turning about its trunk) and a chain of 30 bobs travelling on a
//     ring round it. Seen from the front the ring is a figure of eight: x is
//     one sine of the lap, height is another at a bit over twice the
//     frequency, so the eight slowly drifts into a smile, a frown and back
//     (the "two sine frequencies drift" of the originals). The drift repeats
//     every 60 s, which is the length of the project's theme.
//   * Depth: each bob swaps between six pre-drawn sizes as it goes round (far
//     ones small and dim, near ones big and bright), and every bob exists
//     twice, once on a layer behind the island and once in front, each copy
//     only showing its own half of the lap. So the chain passes behind the
//     palm and in front of her, which one fixed paint order could not do.
//   * Bobs move in whole Amiga pixels: each axis is ONE shared step-end
//     keyframe track, pre-quantised here, and a bob is just that track with
//     its own animation-delay (the "each ball follows the one ahead" chain).
//     The tail bob is a coconut. Nobody has mentioned it.
//   * Dots turn smoothly: a dot at radius r and angle a has x = r sin(a + wt)
//     and y = tilt * r cos(a + wt), each an eased alternate track (one per
//     whole-pixel radius) shifted by its own delay; brightness follows depth.
//   * She sits at the foot of the palm, on the axis, so she never has to turn
//     with it: a billboard sprite, small and simple, nodding on every beat
//     (80 BPM). She has not looked up once.
//   * The tagline under the logo cuts to a new line every two bars of the
//     theme (6 s), ten lines in 60 s. Hard cuts, like the project's own
//     motion rule. During two of them, once a minute, a coconut walks across
//     the front of the island on a hermit crab's legs.
//   * prefers-reduced-motion pauses every track where it starts: a full
//     chain, a turned palm and the first tagline.
// (The .md beside the assets is hand-written, not generated by this script.)

